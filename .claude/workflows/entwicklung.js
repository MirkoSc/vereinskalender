// Taken over from MirkoSc/mitgliederverwaltung (.claude/workflows/entwicklung.js).
// Arguments (all optional, docs/VORGEHEN.md):
//   plan:        [{ n, m: 'opus'|'sonnet'|'haiku', e: 'low'|'medium'|'high'|'xhigh', d: [deps] }]
//                Without it, the plan is read from the open issues labelled "auto"
//                (model/effort from the labels, deps from the "Abhängig von:" line).
//   sammelIssue: collector issue of the round; restricts the plan to the issues it
//                references and receives the report and `braucht-hilfe`.
//   release:     true (next minor version) or { version: 'X.Y.Z' }: afterwards
//                dispatch release.yml as a pre-release.
const SAMMEL = (args && args.sammelIssue) || null
const RELEASE = (args && args.release) || null

const OWNER_REPO = 'MirkoSc/vereinskalender'
const REPO = (args && args.repo) || '/home/user/vereinskalender'
const WT = (args && args.worktrees) || '/home/user/wt'
const MAX_RUNDEN = (args && args.maxRunden) || 3
// Each agent runs its own Docker stack (PHP + MariaDB); more than ~4 at once
// exhausted the session container in the sister project.
const MAX_PARALLEL = (args && args.maxParallel) || 4

const BASIS = `Projekt Vereinskalender: lokales Repository ${REPO}, GitHub ${OWNER_REPO}.
Für dieses Projekt gilt ${REPO}/CLAUDE.md – nicht die CLAUDE.md anderer Projekte.
Du arbeitest vollautomatisch; niemand beantwortet Rückfragen. Bei Unklarheit die einfachste
Lösung wählen, die zu CLAUDE.md passt, und sie im PR unter „Entscheidungen" begründen.
Mirko hat ausdrücklich erlaubt: Branches issue-<nr> pushen, PRs gegen main öffnen, nach Freigabe
in main mergen, Issues kommentieren, labeln und schließen, den Workflow release.yml starten.
GitHub nur über die MCP-Tools mcp__github__* (per ToolSearch laden), nicht über gh.
Docker: prüfe mit "docker info"; läuft es nicht, starte "sudo nohup dockerd > /tmp/dockerd.log 2>&1 &"
und prüfe in einer Schleife erneut. Images kommen von mirror.gcr.io (Docker Hub drosselt).
Fehlt vendor/: "docker compose -p issue-<nr> run --rm --no-deps app composer install".
Holt Composer Pakete als Git-Klon, danach "find vendor -name .git -type d -prune -exec rm -rf {} +"
(sonst ruft PHPUnit git per proc_open auf, das ist im Image gesperrt).
Schwesterprojekt zum Übernehmen von Code (nur lesen, falls vorhanden): /home/user/mitgliederverwaltung.
Jeder Kommentar, den du auf GitHub schreibst, endet mit einer Leerzeile, "---" und der Zeile
"_Generated by [Claude Code](https://claude.ai/code)_".
Skills nutzen, wo sie helfen (bei UI immer frontend-design). Commits auf Englisch.
Migrationen: immer die nächste freie Nummer nach origin/main – der Migrator wendet nur Nummern
> MAX(version) an, eine kleinere Nummer liefe auf bestehenden Installationen nie.
Räume nach den Tests deine Docker-Container ab ("docker compose -p issue-<nr> down -v"), damit der
Speicher reicht. Der Container kann jederzeit neu starten: committe und pushe Zwischenstände regelmäßig
(auch unfertig als "WIP: …" auf issue-<nr>), damit nichts verloren geht.`

const TESTS = n => `"docker compose -p issue-${n} run --rm app vendor/bin/phpunit" und "node --test tests/js/*.test.js"`

const wt = n => `${WT}/issue-${n}`

const IMPL = {
  type: 'object',
  properties: {
    ok: { type: 'boolean' },
    pr: { type: 'number' },
    zusammenfassung: { type: 'string' },
    grund: { type: 'string' },
  },
  required: ['ok', 'zusammenfassung'],
}
const REV = {
  type: 'object',
  properties: {
    freigabe: { type: 'boolean' },
    zusammenfassung: { type: 'string' },
    befunde: { type: 'array', items: { type: 'string' } },
  },
  required: ['freigabe', 'zusammenfassung', 'befunde'],
}
const MERGE = {
  type: 'object',
  properties: { merged: { type: 'boolean' }, grund: { type: 'string' } },
  required: ['merged'],
}

const umsetzenPrompt = i => `${BASIS}

Setze Issue #${i.n} um (Effort: ${i.e}).
1. Worktree anlegen: im Repository ${REPO} "git fetch origin". Existiert origin/issue-${i.n}, dann
   "git worktree add -B issue-${i.n} ${wt(i.n)} origin/issue-${i.n}", sonst
   "git worktree add -B issue-${i.n} ${wt(i.n)} origin/main". Existiert der Worktree schon, weiterverwenden.
   Arbeite ausschließlich in ${wt(i.n)}. Gibt es dort bereits Arbeit (Commits, auch "WIP"),
   mach damit weiter statt neu anzufangen.
2. Folge ${REPO}/.claude/commands/issue.md in der Automatik-Variante: Issue #${i.n} per MCP lesen
   (inkl. Kommentare), die genannten CLAUDE.md-Abschnitte; Abhängigkeiten sind bereits gemergt.
   Implementieren inkl. Pflicht-Tests (CLAUDE.md §11). Testen mit ${TESTS(i.n)}.
3. Committen, dann "git push -u origin issue-${i.n}".
4. Gibt es noch keinen offenen PR für issue-${i.n}: PR per mcp__github__create_pull_request
   (base main, head issue-${i.n}) nach .github/pull_request_template.md: Zusammenfassung,
   „Entscheidungen", Prüfliste für manuelle Tests, am Ende "Closes #${i.n}".
Wenn es wirklich nicht weitergeht: ok=false und Grund. Sonst ok=true und die PR-Nummer.`

const reviewPrompt = (i, pr) => `${BASIS}

Du bist der Reviewer vor dem Merge. Ändere keine Dateien.
PR #${pr} (Branch issue-${i.n}) setzt Issue #${i.n} um. Issue per MCP lesen.
Im Repository ${REPO}: "git fetch origin", dann "git diff origin/main...origin/issue-${i.n}" lesen und die
betroffenen Abschnitte von CLAUDE.md. Tests darfst du im Worktree ${wt(i.n)} ausführen (${TESTS(i.n)}).
Prüfe: Abnahmekriterien und Pflicht-Tests erfüllt? Echte Fehler? Invarianten aus CLAUDE.md verletzt –
insbesondere §1 (kein exec, kurze Requests, PHP 8.5 deprecation-frei), §4 (jeder Schreibweg über Events,
Payload als Vollbild, Upcasting alter Events, Replay-Determinismus), §2 CSP (kein Inline-JS, keine
on*-Attribute), Offline-Parität (PHP-Referenz und JS-Port gleich, Bundle-format bei Shape-Änderung),
§7 (Darstellungsabhängiges nur beim Rendern), Migration neu statt geändert und mit Nummer > der höchsten
auf main? CLAUDE.md bei Architektur-/Datenmodell-Änderung nachgezogen? Deutlich mehr gebaut als verlangt?
Nutze den Skill code-review, wenn er hilft.
Freigabe, wenn nichts davon blockiert. Kleinigkeiten sind kein Ablehnungsgrund. Befunde konkret
(Datei, was falsch, was tun).
Schreibe dein Ergebnis zusätzlich als Kommentar an PR #${pr} (mcp__github__add_issue_comment),
Überschrift "Review (Opus 5.5): Freigabe" bzw. "Review (Opus 5.5): Änderungen nötig".`

const fixPrompt = (i, pr, befunde, runde) => `${BASIS}

Runde ${runde}: Behebe die Review-Befunde für PR #${pr} (Issue #${i.n}) im Worktree ${wt(i.n)}
(Branch issue-${i.n}; fehlt der Worktree, wie üblich aus origin/issue-${i.n} anlegen).
Befunde:
${befunde.map(b => '- ' + b).join('\n')}
Nur diese Punkte, im Umfang des Issues. Tests grün (${TESTS(i.n)}),
committen, "git push origin issue-${i.n}". ok=false nur, wenn es wirklich nicht lösbar ist.`

const mergePrompt = (i, pr) => `${BASIS}

Merge PR #${pr} (Issue #${i.n}), Worktree ${wt(i.n)}, Branch issue-${i.n}.
1. Im Worktree: "git fetch origin" und "git merge origin/main". Konflikte so lösen, dass beide Seiten
   erhalten bleiben (dieses Issue und was inzwischen auf main kam) – auch in CLAUDE.md.
2. Migrationen: hat dieser Branch eine neue Migration und ist ihre Nummer nicht größer als die höchste
   auf origin/main (oder doppelt), die Datei auf die nächste freie Nummer umbenennen (git mv) und
   Verweise darauf (Tests, CLAUDE.md) anpassen.
3. Hat Schritt 1 oder 2 etwas geändert: alle Tests ausführen (${TESTS(i.n)}); ist setup.php betroffen,
   "docker compose -p issue-${i.n} run --rm --no-deps app php bin/build_setup.php" und mitcommitten.
   Fehler minimal beheben, committen, "git push origin issue-${i.n}".
4. PR per mcp__github__merge_pull_request mergen (merge_method squash). Scheitert das, weil main sich
   erneut bewegt hat, Schritte 1–4 wiederholen.
5. Issue #${i.n} schließen (mcp__github__issue_write, state closed, state_reason completed), falls
   noch offen.
6. Aufräumen: "docker compose -p issue-${i.n} down -v" und im Repository ${REPO}
   "git worktree remove --force ${wt(i.n)}".
merged=true nur, wenn der PR wirklich gemergt ist.`

const markierePrompt = (i, grund) => `${BASIS}

Issue #${i.n} ist in der Automatik hängen geblieben. Setze per MCP das Label "braucht-hilfe" am
Issue und schreibe einen Kommentar: "Automatik ist hängen geblieben: ${grund.replace(/"/g, "'")}".
Sonst nichts ändern.`

async function markiere(i, grund) {
  log(`#${i.n} braucht Hilfe: ${grund}`)
  await agent(markierePrompt(i, grund), { label: `markieren #${i.n}`, phase: 'Mergen', model: 'haiku', effort: 'low' })
  return { merged: false }
}

async function bearbeite(i) {
  const offen = offenePrs.get(i.n)
  const impl = offen ? { ok: true, pr: offen, zusammenfassung: 'PR existierte schon' } : await agent(umsetzenPrompt(i), { label: `umsetzen #${i.n}`, phase: 'Umsetzen', model: i.m, effort: i.e, schema: IMPL })
  if (!impl || !impl.ok || !impl.pr) return markiere(i, (impl && impl.grund) || 'Umsetzung ohne PR beendet')
  log(`#${i.n}: PR #${impl.pr} offen`)

  for (let runde = 1; ; runde++) {
    const rev = await agent(reviewPrompt(i, impl.pr), { label: `review #${i.n}`, phase: 'Review', model: 'opus', effort: 'high', schema: REV })
    if (!rev) return markiere(i, 'Review fehlgeschlagen')
    if (rev.freigabe) break
    if (runde > MAX_RUNDEN) return markiere(i, `nach ${MAX_RUNDEN} Runden keine Freigabe: ${rev.befunde.join('; ')}`)
    log(`#${i.n}: Review Runde ${runde} – ${rev.befunde.length} Befunde`)
    const fix = await agent(fixPrompt(i, impl.pr, rev.befunde, runde), { label: `beheben #${i.n} (${runde})`, phase: 'Umsetzen', model: i.m, effort: i.e, schema: IMPL })
    if (!fix || !fix.ok) return markiere(i, (fix && fix.grund) || 'Befunde nicht behebbar')
  }

  const mg = await agent(mergePrompt(i, impl.pr), { label: `mergen #${i.n}`, phase: 'Mergen', model: 'sonnet', effort: 'medium', schema: MERGE })
  if (!mg || !mg.merged) return markiere(i, (mg && mg.grund) || 'Merge fehlgeschlagen')
  log(`#${i.n} gemergt`)
  return { merged: true }
}

phase('Stand')
const stand = await agent(`${BASIS}

Ermittle den Stand in ${OWNER_REPO}. Ändere nichts auf GitHub.
1. Per mcp__github__list_issues (state CLOSED, alle Seiten) die Nummern aller geschlossenen Issues.
2. Per mcp__github__list_pull_requests (state open) alle offenen PRs, deren head-Branch "issue-<nr>"
   heißt (Issue-Nummer und PR-Nummer).
3. Den Plan: alle OFFENEN Issues mit Label "auto" und ohne Label "braucht-hilfe"${SAMMEL ? `, die im Body
   von Sammel-Issue #${SAMMEL} referenziert sind (#<nr>)` : ''}. Je Issue: n = Nummer,
   m = Modell aus dem Label "modell:opus|sonnet|haiku" (fehlt es: "sonnet"),
   e = Effort aus dem Label "effort:low|medium|high|xhigh" (fehlt es: "medium"),
   d = alle Issue-Nummern aus der Zeile "Abhängig von:" im Body (keine: leere Liste).
   Das Sammel-Issue selbst gehört nie in den Plan.
4. Stelle sicher, dass Docker läuft (siehe oben), und lege den Ordner ${WT} an.`, {
  label: 'Stand', model: 'haiku', effort: 'low',
  schema: { type: 'object', properties: {
    geschlossen: { type: 'array', items: { type: 'number' } },
    offene_prs: { type: 'array', items: { type: 'object', properties: { issue: { type: 'number' }, pr: { type: 'number' } }, required: ['issue', 'pr'] } },
    plan: { type: 'array', items: { type: 'object', properties: {
      n: { type: 'number' }, m: { type: 'string', enum: ['opus', 'sonnet', 'haiku'] },
      e: { type: 'string', enum: ['low', 'medium', 'high', 'xhigh'] }, d: { type: 'array', items: { type: 'number' } } },
      required: ['n', 'm', 'e', 'd'] } },
    docker_ok: { type: 'boolean' } }, required: ['geschlossen', 'offene_prs', 'plan', 'docker_ok'] },
})
if (!stand) throw new Error('Stand konnte nicht ermittelt werden')
if (!stand.docker_ok) log('Warnung: Docker läuft nicht – die Agenten versuchen es selbst zu starten')

const PLAN = (args && args.plan) || stand.plan
const done = new Set(stand.geschlossen)
const offenePrs = new Map(stand.offene_prs.map(x => [x.issue, x.pr]))
const failed = new Set()
const pending = PLAN.filter(i => !done.has(i.n))
const running = new Map()
log(`Plan: ${PLAN.map(i => `#${i.n} (${i.m}/${i.e}${i.d.length ? ', nach ' + i.d.map(x => '#' + x).join(' ') : ''})`).join(', ') || 'leer'}`)
log(`${pending.length} offen, ${offenePrs.size} mit offenem PR`)

// A dependency that is neither closed nor part of this run can never be met.
const imPlan = new Set(PLAN.map(i => i.n))
for (const i of [...pending]) {
  const fremd = i.d.filter(x => !done.has(x) && !imPlan.has(x))
  if (fremd.length) {
    pending.splice(pending.indexOf(i), 1)
    failed.add(i.n)
    await markiere(i, `Abhängigkeit ${fremd.map(x => '#' + x).join(', ')} ist offen, aber nicht Teil der Runde`)
  }
}

while (pending.length || running.size) {
  for (const i of [...pending]) {
    if (i.d.some(x => failed.has(x))) {
      pending.splice(pending.indexOf(i), 1)
      failed.add(i.n)
      log(`#${i.n} übersprungen – Abhängigkeit hängt`)
    } else if (running.size < MAX_PARALLEL && i.d.every(x => done.has(x))) {
      pending.splice(pending.indexOf(i), 1)
      running.set(i.n, bearbeite(i).catch(e => ({ merged: false, err: String(e) })).then(r => ({ i, r })))
      log(`#${i.n} gestartet (${i.m}, ${i.e})`)
    }
  }
  if (!running.size) break
  const { i, r } = await Promise.race(running.values())
  running.delete(i.n)
  if (r && r.merged) done.add(i.n)
  else failed.add(i.n)
}

const gemergt = PLAN.filter(i => done.has(i.n)).map(i => i.n)
const haengt = [...failed].sort((a, b) => a - b)
let release = null

const sammelMelden = async grund => {
  log(SAMMEL ? `Sammel-Issue #${SAMMEL}: ${grund}` : grund)
  if (!SAMMEL) return
  await agent(`${BASIS}

Setze per MCP am Issue #${SAMMEL} das Label "braucht-hilfe" und schreibe einen Kommentar
"Automatik ist hängen geblieben: ${grund.replace(/"/g, "'")}". Sonst nichts ändern.`,
    { label: `melden #${SAMMEL}`, phase: 'Release', model: 'haiku', effort: 'low' })
}

if (haengt.length || pending.length) {
  await sammelMelden(`Nicht gemergt: ${[...haengt, ...pending.map(i => i.n)].map(n => '#' + n).join(', ')}` +
    (RELEASE ? ' – deshalb kein Release.' : '.') + ' Gründe stehen an den Issues.')
} else if (RELEASE && gemergt.length) {
  release = await releasePhase(typeof RELEASE === 'object' ? RELEASE.version : null)
} else if (RELEASE) {
  log('Nichts gemergt – kein Release.')
}

return { gemergt, haengt_oder_uebersprungen: haengt, nicht_gestartet: pending.map(i => i.n), release }

async function releasePhase(wunschVersion) {
  phase('Release')
  const ci = await agent(`${BASIS}

Warte, bis die CI auf main grün ist (${OWNER_REPO}). Ändere nichts.
1. SHA des neuesten Commits auf main per mcp__github__list_commits (sha "main", perPage 1).
2. Lauf von ci.yml zu genau diesem Commit: mcp__github__actions_list, method list_workflow_runs,
   resource_id "ci.yml", workflow_runs_filter {branch: "main", event: "push"}; der Lauf mit head_sha == SHA.
3. Fehlt er noch oder ist er nicht "completed": etwa 2 Minuten warten (Monitor-Tool oder ein Bash-Befehl im
   Hintergrund) und erneut prüfen, höchstens 45 Minuten insgesamt.
Ergebnis: ok=true nur bei conclusion "success"; sonst ok=false mit Grund (conclusion bzw. Zeitüberschreitung)
und dem Link zum Lauf.`, {
    label: 'CI auf main', phase: 'Release', model: 'sonnet', effort: 'low',
    schema: { type: 'object', properties: { ok: { type: 'boolean' }, sha: { type: 'string' }, lauf: { type: 'string' }, grund: { type: 'string' } }, required: ['ok', 'sha'] },
  })
  if (!ci || !ci.ok) {
    await sammelMelden(`CI auf main nicht grün (${(ci && (ci.grund || ci.lauf)) || 'nicht ermittelt'}) – kein Release.`)
    return { ok: false }
  }

  const versionSchritt = wunschVersion
    ? `Version: ${wunschVersion}.`
    : `Version bestimmen: per mcp__github__list_releases (alle Seiten, inkl. Pre-Releases) die höchste Version
   X.Y.Z (Tag "vX.Y.Z", semantisch verglichen); die neue Version ist X.(Y+1).0.`
  const rel = await agent(`${BASIS}

Löse ein Pre-Release aus und prüfe es (${OWNER_REPO}). Erstelle das Release NIE selbst per MCP (das umginge
den Build) – nur über den Workflow release.yml.
0. ${versionSchritt}
   mcp__github__get_release_by_tag "v<Version>": Gibt es es schon und zeigt der Tag auf ${ci.sha}, weiter mit 4.
   Gibt es den Tag schon für einen anderen Commit: ok=false mit Grund.
1. mcp__github__actions_run_trigger: method run_workflow, workflow_id "release.yml", ref "main",
   inputs {"version": "<Version>"}.
2. Den Lauf finden: mcp__github__actions_list, list_workflow_runs, resource_id "release.yml",
   workflow_runs_filter {event: "workflow_dispatch"}; der neueste Lauf mit head_sha == ${ci.sha}.
3. Bis "completed" etwa alle 2 Minuten prüfen (höchstens 40 Minuten). Bei conclusion != "success": die Logs der
   fehlgeschlagenen Jobs lesen (mcp__github__get_job_logs, nur fehlgeschlagene) und den Grund kurz nennen – ok=false.
4. Prüfen per mcp__github__get_release_by_tag "v<Version>": prerelease == true; Dateien
   vereinskalender-v<Version>.zip, setup.php und checksums.txt vorhanden, Größe > 0.
Ergebnis: ok, version (ohne "v"), Link zum Release, Link zum Lauf, Größe des ZIP in MB, ggf. Grund.`, {
    label: 'Release', phase: 'Release', model: 'sonnet', effort: 'medium',
    schema: { type: 'object', properties: { ok: { type: 'boolean' }, version: { type: 'string' }, release: { type: 'string' }, lauf: { type: 'string' }, zip_mb: { type: 'number' }, grund: { type: 'string' } }, required: ['ok'] },
  })
  if (!rel || !rel.ok) {
    await sammelMelden(`Pre-Release ${(rel && rel.version) || wunschVersion || ''} gescheitert: ${(rel && rel.grund) || 'unbekannt'} ${(rel && rel.lauf) || ''}`)
    return { ok: false }
  }

  if (SAMMEL) {
    await agent(`${BASIS}

Schreibe den Abschlussbericht der Runde als Kommentar an Issue #${SAMMEL} (mcp__github__add_issue_comment).
Ändere sonst nichts. Kurz und auf Deutsch, für Mirko (nicht technisch):
- Überschrift "Pre-Release v${rel.version} ist fertig" mit Link ${rel.release}
- gemergte Issues mit ihren PRs (je eine Zeile, Titel per MCP lesen): ${gemergt.map(n => '#' + n).join(', ')}
- CI-Lauf: ${ci.lauf || '–'}, Release-Lauf: ${rel.lauf || '–'}, Größe des ZIP: ${rel.zip_mb || '?'} MB
- Was Mirko jetzt tun kann: Testinstanz (Update-Kanal beta) im Admin unter „Update" aktualisieren, die
  geänderten Seiten am Handy und am PC ansehen, dann das Release auf GitHub als „latest" markieren –
  erst dann zieht die Produktivinstanz (Kanal stable) nach. Wenn alles passt, dieses Issue schließen.`,
      { label: `Bericht #${SAMMEL}`, phase: 'Release', model: 'sonnet', effort: 'low' })
  }
  log(`Pre-Release v${rel.version}: ${rel.release}`)
  return { ok: true, version: rel.version, release: rel.release }
}
